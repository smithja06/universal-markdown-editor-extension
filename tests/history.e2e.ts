import { test, expect, type Page } from '@playwright/test'

const visual = (page: Page) => page.getByRole('textbox', { name: 'Visual document editor' })
const source = (page: Page) => page.getByRole('textbox', { name: 'Markdown source editor' })
const history = (page: Page) => page.getByRole('dialog', { name: 'Version History' })
const versions = (page: Page) => history(page).getByRole('button', { name: /Preview version/ })

async function menu(page: Page, action: string) {
  await page.getByRole('button', { name: 'File', exact: true }).click()
  await page.getByRole('menuitem', { name: action, exact: true }).click()
}

async function editSource(page: Page, value: string) {
  await source(page).click()
  await page.keyboard.press('ControlOrMeta+a')
  await page.keyboard.insertText(value)
}

async function seedLegacyWorkspace(page: Page, keepOpen = false) {
  await page.route('**/legacy-history-fixture', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><title>Legacy workspace fixture</title>' }))
  await page.goto('/legacy-history-fixture')
  await page.evaluate(async keepConnection => {
    await new Promise<void>((resolve, reject) => {
      const request = indexedDB.open('folio-workspace', 1)
      request.onupgradeneeded = () => {
        const file = { id: 'legacy-id', title: 'Legacy file', savedTitle: 'Legacy file', source: '# Legacy draft\n', savedSource: '# Legacy draft\n', bom: true, lineEnding: '\r\n', updated: 1000 }
        request.result.createObjectStore('sessions').put({ currentId: file.id, files: [file] }, 'current')
      }
      request.onsuccess = () => {
        if (keepConnection) Reflect.set(window, 'legacyWorkspaceConnection', request.result)
        else request.result.close()
        resolve()
      }
      request.onerror = () => reject(request.error ?? new Error('Could not open the legacy workspace fixture.'))
    })
  }, keepOpen)
}

test('automatic and manual versions deduplicate, preview read-only, and survive a reload', async ({ page }) => {
  await page.goto('/')
  await expect(visual(page)).toContainText('Welcome to Folio')
  await menu(page, 'Version History')
  await expect(versions(page)).toHaveCount(1)
  await expect(versions(page).first()).toContainText('Automatic')
  await history(page).getByRole('button', { name: 'Close dialog' }).click()

  await page.clock.setFixedTime(new Date(Date.now() + 65_000))
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  await editSource(page, '# Project notes\n\n**A bold draft** and $x^2$.\n')
  await expect(page.getByTitle('Saved locally')).toBeVisible()
  await menu(page, 'Version History')
  await expect(versions(page)).toHaveCount(2)
  await expect(versions(page).first()).toContainText('Automatic')
  await history(page).getByRole('button', { name: 'Create version', exact: true }).click()
  await expect(versions(page)).toHaveCount(2)
  await expect(versions(page).first()).toContainText('Manual')
  await history(page).getByRole('button', { name: 'Create version', exact: true }).click()
  await expect(history(page).getByRole('status').filter({ hasText: 'already saved' })).toBeVisible()
  await expect(versions(page)).toHaveCount(2)
  await page.reload()
  await expect(source(page)).toContainText('# Project notes')
  await menu(page, 'Version History')
  await expect(versions(page)).toHaveCount(2)
  await versions(page).first().click()
  const preview = page.frameLocator('iframe[title="Rendered version preview"]')
  await expect(preview.getByRole('heading', { name: 'Project notes' })).toBeVisible()
  await expect(preview.locator('strong')).toHaveText('A bold draft')
  await expect(preview.locator('math')).toBeVisible()
  await expect(preview.locator('[contenteditable]')).toHaveCount(0)
  await history(page).getByRole('button', { name: 'Markdown', exact: true }).click()
  await expect(history(page).getByRole('region', { name: 'Markdown version preview' })).toContainText('**A bold draft**')
})

test('a version restored in split mode updates both panes and keeps an immediately recoverable draft', async ({ page }) => {
  await page.goto('/')
  await expect(visual(page)).toContainText('Welcome to Folio')
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  const original = '---\nauthor: Original\ncustom: retained\n---\n\n# Before\n\n:::widget\nPreserved block\n:::\n'
  const current = '# Latest work\n\nA draft I may want back.\n'
  await editSource(page, original)
  await menu(page, 'Version History')
  await history(page).getByRole('button', { name: 'Create version' }).click()
  await expect(versions(page).first()).toContainText('Manual')
  await history(page).getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Split Editor', exact: true }).click()
  await editSource(page, current)
  await expect(visual(page).getByRole('heading', { name: 'Latest work' })).toBeVisible()
  await menu(page, 'Version History')
  await versions(page).first().click()
  await expect(page.frameLocator('iframe[title="Rendered version preview"]').getByRole('heading', { name: 'Before' })).toBeVisible()
  await history(page).getByRole('button', { name: 'Restore version' }).click()
  await expect(history(page).getByText(/keep your current draft in history/i)).toBeVisible()
  await history(page).getByRole('button', { name: 'Cancel restore' }).click()
  await expect(versions(page).first()).toContainText('Manual')
  await history(page).getByRole('button', { name: 'Restore version' }).click()
  await history(page).getByRole('button', { name: 'Confirm restore' }).click()
  await expect(history(page)).toHaveCount(0)
  await expect(visual(page).getByRole('heading', { name: 'Before' })).toBeVisible()
  await expect(source(page)).toContainText('custom: retained')
  await expect(source(page)).toContainText(':::widget')
  await expect(page.getByRole('navigation', { name: 'Document outline' }).getByRole('button', { name: 'H1 Before', exact: true })).toBeVisible()
  await page.reload()
  await expect(visual(page).getByRole('heading', { name: 'Before' })).toBeVisible()
  await menu(page, 'Version History')
  await versions(page).filter({ hasText: 'Recovery' }).click()
  await expect(page.frameLocator('iframe[title="Rendered version preview"]').getByRole('heading', { name: 'Latest work' })).toBeVisible()
  await expect(versions(page).filter({ hasText: 'Manual' })).toHaveCount(1)
  await history(page).getByRole('button', { name: 'Restore version' }).click()
  await history(page).getByRole('button', { name: 'Confirm restore' }).click()
  await expect(history(page)).toHaveCount(0)
  await expect(visual(page).getByRole('heading', { name: 'Latest work' })).toBeVisible()
})

test('a failed history write is visible and a failed restore preserves the current saved draft', async ({ page }) => {
  await page.goto('/')
  await expect(visual(page)).toContainText('Welcome to Folio')
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  await editSource(page, '# Keep this current draft\n')
  await expect(page.getByTitle('Saved locally')).toBeVisible()
  await menu(page, 'Version History')
  await expect(versions(page)).toHaveCount(1)
  await page.evaluate(() => {
    const { add, put } = IDBObjectStore.prototype
    IDBObjectStore.prototype.add = function (this: IDBObjectStore, value, key) {
      if (this.name === 'document-versions') throw new DOMException('Quota exceeded', 'QuotaExceededError')
      return add.call(this, value, key)
    }
    Reflect.set(window, 'failRestoreWrite', () => {
      IDBObjectStore.prototype.add = add
      IDBObjectStore.prototype.put = function (this: IDBObjectStore, value, key) {
        if (this.name === 'document-drafts') throw new DOMException('Quota exceeded', 'QuotaExceededError')
        return put.call(this, value, key)
      }
    })
  })
  await history(page).getByRole('button', { name: 'Create version' }).click()
  await expect(history(page).getByRole('alert')).toContainText(/storage is full/i)
  await expect(versions(page)).toHaveCount(1)
  await page.evaluate(() => Reflect.get(window, 'failRestoreWrite')())
  await versions(page).first().click()
  await history(page).getByRole('button', { name: 'Restore version' }).click()
  await history(page).getByRole('button', { name: 'Confirm restore' }).click()
  await expect(history(page).getByRole('alert')).toContainText(/storage is full/i)
  await expect(versions(page)).toHaveCount(1)
  await history(page).getByRole('button', { name: 'Close dialog' }).click()
  await expect(source(page)).toContainText('Keep this current draft')
  await page.reload()
  await expect(source(page)).toContainText('# Keep this current draft')
  await menu(page, 'Version History')
  await expect(versions(page).filter({ hasText: 'Recovery' })).toHaveCount(0)
})

test('upgrades a version-one workspace and checkpoints the outgoing document under its original ID', async ({ page }) => {
  await seedLegacyWorkspace(page)
  await page.goto('/')
  await expect(visual(page).getByRole('heading', { name: 'Legacy draft' })).toBeVisible()
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  await editSource(page, '# Legacy draft\n\nKept when opening another document.\n')
  await menu(page, 'New document')
  await expect(page.getByRole('textbox', { name: 'Document name' })).toHaveValue('Untitled document')
  await menu(page, 'Version History')
  await expect(versions(page)).toHaveCount(1)
  await expect(versions(page).first()).toContainText('Untitled document')
  await history(page).getByRole('button', { name: 'Close dialog' }).click()
  await menu(page, 'Recent documents')
  await page.getByRole('dialog', { name: 'Recent documents' }).getByRole('button', { name: 'Legacy file' }).click()
  await expect(source(page)).toContainText('Kept when opening another document.')
  await page.setViewportSize({ width: 430, height: 780 })
  await menu(page, 'Version History')
  await expect(versions(page)).toHaveCount(2)
  await versions(page).first().click()
  await expect(page.frameLocator('iframe[title="Rendered version preview"]').getByText('Kept when opening another document.')).toBeVisible()
  expect(await history(page).evaluate(element => element.scrollWidth)).toBeLessThanOrEqual(430)
})

test('a blocked workspace upgrade reports the problem on retries and recovers after the older tab closes', async ({ page, context }) => {
  const older = await context.newPage()
  await seedLegacyWorkspace(older, true)
  await page.goto('/')
  await expect(page.getByTitle('Local storage unavailable')).toBeVisible()
  await menu(page, 'Version History')
  await expect(history(page).getByRole('alert')).toContainText('Close older Folio tabs')
  await history(page).getByRole('button', { name: 'Retry loading versions' }).click()
  await expect(history(page).getByRole('alert')).toContainText('Close older Folio tabs')
  const create = history(page).getByRole('button', { name: 'Create version', exact: true })
  await create.click()
  await expect(create).toBeEnabled()
  await expect(history(page).getByRole('alert')).toContainText('Close older Folio tabs')
  await older.close()
  await page.reload()
  await expect(visual(page).getByRole('heading', { name: 'Legacy draft' })).toBeVisible()
  await menu(page, 'Version History')
  await expect(versions(page)).toHaveCount(1)
})

test('a manual checkpoint defers an automatic checkpoint without skipping later idle edits', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await expect(visual(page)).toContainText('Welcome to Folio')
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  await editSource(page, '# Manual checkpoint\n')
  await page.clock.fastForward(30_000)
  await menu(page, 'Version History')
  await history(page).getByRole('button', { name: 'Create version' }).click()
  await expect(versions(page).first()).toContainText('Manual')
  await history(page).getByRole('button', { name: 'Close dialog' }).click()
  await editSource(page, '# Saved while idle\n')
  await page.clock.fastForward(31_000)
  await menu(page, 'Version History')
  await expect(versions(page)).toHaveCount(2)
  await history(page).getByRole('button', { name: 'Close dialog' }).click()
  await page.clock.fastForward(31_000)
  await menu(page, 'Version History')
  await expect(versions(page)).toHaveCount(3)
  await versions(page).first().click()
  await expect(page.frameLocator('iframe[title="Rendered version preview"]').getByRole('heading', { name: 'Saved while idle' })).toBeVisible()
})
