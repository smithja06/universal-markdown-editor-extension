test('suggests verified functions with argument hints in the formula bar and the cell editor', async ({ page }) => {
  await menu(page, 'File', 'New spreadsheet')
  await enter(page, 'A1', '3')
  await enter(page, 'A2', '4')
  await cell(page, 'B1').click()
  const formula = page.getByRole('textbox', { name: 'Formula bar' })
  await formula.click()
  await formula.pressSequentially('=su')
  const list = page.getByRole('listbox', { name: 'Function suggestions' })
  await expect(list.getByRole('option').first()).toHaveText(/SUM/)
  await expect(formula).toHaveAttribute('aria-controls', /.+/)
  await formula.press('ArrowDown')
  await expect(list.getByRole('option', { name: /SUMPRODUCT/ })).toHaveAttribute('aria-selected', 'true')
  await page.screenshot({ path: 'test-results/formula-assist.png', clip: { x: 0, y: 60, width: 900, height: 360 } })
  await formula.press('ArrowUp')
  await formula.press('Tab')
  await expect(formula).toHaveValue('=SUM(')
  await expect(page.getByRole('group', { name: 'Formula help' })).toContainText('Adds numbers or cell ranges.')
  await formula.pressSequentially('A1:A2')
  await expect(page.getByLabel('SUM arguments').locator('mark')).toHaveText('number1')
  await formula.pressSequentially(')')
  await formula.press('Enter')
  await expect(cell(page, 'B1')).toContainText('7')

  await cell(page, 'B2').dblclick()
  const editor = page.getByRole('textbox', { name: 'Edit B2' })
  await editor.pressSequentially('=roun')
  await expect(list.getByRole('option').first()).toHaveText(/ROUND/)
  await editor.press('Enter')
  await expect(editor).toHaveValue('=ROUND(')
  await editor.pressSequentially('A1/A2, ')
  await expect(page.getByLabel('ROUND arguments').locator('mark')).toHaveText('digits')
  await editor.pressSequentially('2)')
  await editor.press('Enter')
  await expect(cell(page, 'B2')).toContainText('0.75')

  await cell(page, 'B3').click()
  await formula.click()
  await formula.pressSequentially('=OFFSET(A1, 1, 0)')
  await expect(page.getByRole('group', { name: 'Formula help' })).toContainText('OFFSET is not in Folio’s supported formula list')
  await formula.press('Escape')
  await expect(page.getByRole('group', { name: 'Formula help' })).toHaveCount(0)
})
