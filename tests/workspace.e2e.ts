test('a failed local write keeps an edited tab open until its draft can be saved', async ({ page }) => {
  await start(page)
  await expect(page.getByTitle('Saved locally')).toBeVisible()
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  await page.evaluate(() => {
    const put = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (this: IDBObjectStore, value, key) {
      if (this.name === 'document-drafts') throw new DOMException('Storage full', 'QuotaExceededError')
      return put.call(this, value, key)
    }
    Reflect.set(window, 'restoreDraftWrites', () => { IDBObjectStore.prototype.put = put })
  })
  await replaceSource(page, '# Keep the unsaved draft\n')
  await page.getByRole('button', { name: 'Close Getting started' }).click()
  await expect(page.getByText(/This draft could not be saved locally/)).toBeVisible()
  await expect(tab(page, 'Getting started')).toHaveAttribute('aria-selected', 'true')
  await expect(source(page)).toContainText('Keep the unsaved draft')
  await page.evaluate(() => Reflect.get(window, 'restoreDraftWrites')())
  await page.getByRole('button', { name: 'Close Getting started' }).click()
  await expect(page.getByRole('heading', { name: 'No open documents' })).toBeVisible()
  await menu(page, 'Tab actions', 'Reopen closed tab')
  await expect(source(page)).toContainText('Keep the unsaved draft')
})

test('a delayed file save updates only the document that started it', async ({ page }) => {
  await start(page)
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  await page.evaluate(() => {
    Reflect.set(window, 'showSaveFilePicker', () => new Promise(resolve => Reflect.set(window, 'finishFileSave', () => resolve({
      name: 'First.md',
      createWritable: async () => ({
        write: async (bytes: Uint8Array) => { Reflect.set(window, 'savedFileText', new TextDecoder().decode(bytes)) },
        close: async () => {}, abort: async () => {},
      }),
    }))))
  })
  await replaceSource(page, '# First draft at save time\n')
  await menu(page, 'File', 'Save Ctrl+S')
  await page.waitForFunction(() => typeof Reflect.get(window, 'finishFileSave') === 'function')
  await replaceSource(page, '# First draft after starting save\n')
  await page.getByRole('button', { name: 'New document tab' }).click()
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  await replaceSource(page, '# Second draft\n')
  await page.evaluate(() => Reflect.get(window, 'finishFileSave')())
  await expect(page.getByText('Saved to First.md', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => Reflect.get(window, 'savedFileText'))).toBe('# First draft at save time\n')
  await expect(tab(page, 'Untitled document')).toHaveAttribute('aria-selected', 'true')
  await expect(source(page)).toContainText('Second draft')
  await tab(page, 'Getting started').click()
  await expect(source(page)).toContainText('First draft after starting save')
  await expect(tab(page, 'Getting started')).toHaveAttribute('aria-description', 'Changes since last file save')
})

test('many open tabs stay usable on mobile and expose contextual actions and keyboard focus', async ({ page }) => {
  await start(page)
  const name = page.getByRole('textbox', { name: 'Document name' })
  await name.fill('Renamed before opening a tab')
  const newTab = page.getByRole('button', { name: 'New document tab' })
  for (let index = 0; index < 16; index++) await newTab.click()
  const strip = page.getByRole('tablist', { name: 'Open documents' })
  await expect(strip.getByRole('tab')).toHaveCount(17)
  await expect(tab(page, 'Renamed before opening a tab')).toHaveCount(1)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await strip.evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true)
  expect(await page.locator('body').evaluate(element => element.scrollWidth)).toBeLessThanOrEqual(390)
  await tab(page, 'Renamed before opening a tab').click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Close Renamed before opening a tab' }).click()
  await expect(strip.getByRole('tab')).toHaveCount(16)
  await expect(tab(page, 'Untitled document (16)')).toBeFocused()
  await tab(page, 'Untitled document (16)').press('ArrowLeft')
  await expect(tab(page, 'Untitled document (15)')).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: 'Open document library' }).click()
  await expect(library(page).getByRole('listitem')).toHaveCount(17)
  expect(await library(page).evaluate(element => element.scrollWidth)).toBeLessThanOrEqual(390)
})
