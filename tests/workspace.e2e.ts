import { expect, test, type Page } from '@playwright/test'

const visual = (page: Page) => page.getByRole('textbox', { name: 'Visual document editor' })
const source = (page: Page) => page.getByRole('textbox', { name: 'Markdown source editor' })
const tab = (page: Page, name: string) => page.getByRole('tab', { name, exact: true })
const library = (page: Page) => page.getByRole('dialog', { name: 'Document library' })
const history = (page: Page) => page.getByRole('dialog', { name: 'Version History' })

async function start(page: Page) {
  await page.goto('/')
  await expect(visual(page)).toContainText('Welcome to Folio')
}

async function menu(page: Page, label: string, action: string) {
  await page.getByRole('button', { name: label, exact: true }).click()
  await page.getByRole('menuitem', { name: action, exact: true }).click()
}

async function replaceSource(page: Page, markdown: string) {
  await source(page).click()
  await page.keyboard.press('ControlOrMeta+a')
  await page.keyboard.insertText(markdown)
}

async function importFile(page: Page, filename: string, markdown: string) {
  await page.locator('input[accept^=".md"]').setInputFiles({ name: filename, mimeType: 'text/markdown', buffer: Buffer.from(markdown) })
}

test('rapid switches persist each exact draft and restore the active tab and editing modes after reload', async ({ page }) => {
  await start(page)
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  await page.getByRole('button', { name: 'New document tab' }).click()
  await page.getByRole('button', { name: 'Split Editor', exact: true }).click()

  for (let edit = 1; edit <= 3; edit++) {
    await tab(page, 'Getting started').click()
    await expect(page.getByRole('button', { name: 'Markdown Source', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await replaceSource(page, `# Alpha ${edit}\n\nOnly in the first document.\n`)
    await tab(page, 'Untitled document').click()
    await expect(page.getByRole('button', { name: 'Split Editor', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await replaceSource(page, `# Bravo ${edit}\n\nOnly in the second document.\n`)
  }
  await tab(page, 'Getting started').click()
  await expect(source(page)).toContainText('Alpha 3')
  await expect(source(page)).not.toContainText('Bravo')
  await expect(tab(page, 'Getting started')).toHaveAttribute('aria-description', 'Changes since last file save')
  await expect(page.getByTitle('Saved locally')).toBeVisible()
  await page.reload()
  await expect(tab(page, 'Getting started')).toHaveAttribute('aria-selected', 'true')
  await expect(source(page)).toBeVisible()
  await expect(source(page)).toContainText('Alpha 3')
  await tab(page, 'Untitled document').click()
  await expect(source(page)).toContainText('Bravo 3')
  await expect(visual(page).getByRole('heading', { name: 'Bravo 3' })).toBeVisible()
  await expect(page.locator('.tiptap')).toHaveCount(1)
  await expect(page.locator('.cm-editor')).toHaveCount(1)
})

test('open tabs preserve their cursor, scroll, and independent source and visual undo histories', async ({ page }) => {
  await start(page)
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  const lines = Array.from({ length: 110 }, (_, index) => `Line ${index + 1}`)
  await replaceSource(page, lines.join('\n\n'))
  await expect(page.getByTitle('Saved locally')).toBeVisible()
  await page.getByRole('button', { name: 'New document tab' }).click()
  await visual(page).click()
  await page.keyboard.insertText('Second tab can undo this')

  await tab(page, 'Getting started').click()
  await source(page).focus()
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.insertText(' appended')
  await expect(source(page)).toContainText('Line 110 appended')
  const before = await page.locator('.cm-scroller').evaluate(node => node.scrollTop)
  await expect(page.getByText(/Ln 219, Col 18/)).toBeVisible()
  await tab(page, 'Untitled document').click()
  await expect(visual(page)).toContainText('Second tab can undo this')
  await page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true }).click()
  await expect(visual(page)).not.toContainText('Second tab can undo this')

  await tab(page, 'Getting started').click()
  await expect(page.getByText(/Ln 219, Col 18/)).toBeVisible()
  await expect.poll(() => page.locator('.cm-scroller').evaluate(node => node.scrollTop)).toBeGreaterThan(Math.max(0, before - 100))
  await page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true }).click()
  await expect(source(page)).toContainText('Line 110')
  await expect(source(page)).not.toContainText('appended')
  await page.getByRole('button', { name: 'Redo (Ctrl+Shift+Z)', exact: true }).click()
  await expect(source(page)).toContainText('Line 110 appended')
  await expect(page.getByTitle('Saved locally')).toBeVisible()
  await page.reload()
  await expect(page.getByText(/Ln 219, Col 18/)).toBeVisible()
  await expect.poll(() => page.locator('.cm-scroller').evaluate(node => node.scrollTop)).toBeGreaterThan(0)
})

test('the library disambiguates imports, searches and sorts, and can rename, duplicate, trash and recover documents', async ({ page }) => {
  await start(page)
  await importFile(page, 'Notes.md', '# First import\n')
  await expect(tab(page, 'Notes')).toHaveAttribute('aria-selected', 'true')
  await importFile(page, 'Notes.md', '# Second import\n')
  await expect(tab(page, 'Notes (2)')).toHaveAttribute('aria-selected', 'true')
  await expect(visual(page).getByRole('heading', { name: 'Second import' })).toBeVisible()
  await tab(page, 'Notes').click()
  await expect(visual(page).getByRole('heading', { name: 'First import' })).toBeVisible()

  await page.getByRole('button', { name: 'Open document library' }).click()
  await library(page).getByRole('searchbox', { name: 'Search documents' }).fill('notes')
  await library(page).getByRole('combobox', { name: 'Sort documents' }).selectOption('descending')
  await expect(library(page).getByRole('listitem')).toHaveCount(2)
  await expect(library(page).getByRole('listitem').first()).toContainText('Notes (2)')
  await library(page).getByRole('button', { name: 'Rename Notes', exact: true }).click()
  await library(page).getByRole('textbox', { name: 'Document name' }).fill('Reference notes')
  await library(page).getByRole('button', { name: 'Save name' }).click()
  await expect(library(page).getByRole('button', { name: 'Reference notes', exact: true })).toBeVisible()
  await library(page).getByRole('button', { name: 'Duplicate Reference notes', exact: true }).click()
  await expect(tab(page, 'Reference notes copy')).toHaveAttribute('aria-selected', 'true')
  await expect(visual(page).getByRole('heading', { name: 'First import' })).toBeVisible()

  await page.getByRole('button', { name: 'Open document library' }).click()
  await library(page).getByRole('button', { name: 'Delete Reference notes copy', exact: true }).click()
  await expect(library(page).getByText(/its open tab will close/i)).toBeVisible()
  await library(page).getByRole('button', { name: 'Move to Trash' }).click()
  await expect(tab(page, 'Reference notes copy')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: 'Open document library' }).click()
  await library(page).getByRole('button', { name: 'Trash', exact: true }).click()
  await library(page).getByRole('button', { name: 'Restore Reference notes copy' }).click()
  await library(page).getByRole('button', { name: 'All documents' }).click()
  await library(page).getByRole('button', { name: 'Reference notes copy', exact: true }).click()
  await expect(visual(page).getByRole('heading', { name: 'First import' })).toBeVisible()
})

test('restoring a version and recovering a deleted tab never change a different document', async ({ page }) => {
  await start(page)
  await importFile(page, 'History.md', '# Early notes\n')
  await expect(tab(page, 'History')).toHaveAttribute('aria-selected', 'true')
  await menu(page, 'File', 'Version History')
  await history(page).getByRole('button', { name: 'Create version' }).click()
  await expect(history(page).getByRole('button', { name: /Preview version.*Manual/ })).toBeVisible()
  await history(page).getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Split Editor', exact: true }).click()
  await replaceSource(page, '# Recover these notes\n')
  await importFile(page, 'History.md', '# Independent notes\n')
  await expect(tab(page, 'History (2)')).toHaveAttribute('aria-selected', 'true')
  await menu(page, 'File', 'Version History')
  await expect(history(page).getByRole('button', { name: /Preview version/ })).toHaveCount(1)
  await expect(history(page).getByRole('button', { name: /Preview version.*Manual/ })).toHaveCount(0)
  await history(page).getByRole('button', { name: 'Close dialog' }).click()

  await tab(page, 'History').click()
  await menu(page, 'File', 'Version History')
  await history(page).getByRole('button', { name: /Preview version.*Manual/ }).click()
  await history(page).getByRole('button', { name: 'Restore version' }).click()
  await history(page).getByRole('button', { name: 'Confirm restore' }).click()
  await expect(source(page)).toContainText('Early notes')
  await expect(visual(page).getByRole('heading', { name: 'Early notes' })).toBeVisible()
  await tab(page, 'History (2)').click()
  await expect(visual(page).getByRole('heading', { name: 'Independent notes' })).toBeVisible()

  await page.getByRole('button', { name: 'Open document library' }).click()
  await library(page).getByRole('button', { name: 'Delete History', exact: true }).click()
  await library(page).getByRole('button', { name: 'Move to Trash' }).click()
  await expect(tab(page, 'History')).toHaveCount(0)
  await library(page).getByRole('button', { name: 'Trash', exact: true }).click()
  await library(page).getByRole('button', { name: 'Restore History', exact: true }).click()
  await library(page).getByRole('button', { name: 'All documents' }).click()
  await library(page).getByRole('button', { name: 'History', exact: true }).click()
  await menu(page, 'File', 'Version History')
  await history(page).getByRole('button', { name: /Preview version.*Recovery/ }).click()
  await expect(page.frameLocator('iframe[title="Rendered version preview"]').getByRole('heading', { name: 'Recover these notes' })).toBeVisible()
})

