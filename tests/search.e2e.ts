import { readFile } from 'node:fs/promises'
import { expect, test, type Page } from '@playwright/test'

const visual = (page: Page) => page.getByRole('textbox', { name: 'Visual document editor' })
const source = (page: Page) => page.getByRole('textbox', { name: 'Markdown source editor' })
const panel = (page: Page) => page.getByRole('region', { name: 'Find and replace' })
const query = (page: Page) => panel(page).getByRole('textbox', { name: 'Find text' })
const palette = (page: Page) => page.getByRole('dialog', { name: 'Command Palette' })

async function open(page: Page, file: string, markdown: string) {
  await page.locator('input[accept^=".md"]').setInputFiles({ name: file + '.md', mimeType: 'text/markdown', buffer: Buffer.from(markdown) })
  await expect(page.getByRole('tab', { name: file, exact: true })).toHaveAttribute('aria-selected', 'true')
}

async function start(page: Page) {
  await page.goto('/')
  await expect(visual(page)).toContainText('Welcome to Folio')
}

async function menu(page: Page, label: string, command: string) {
  await page.getByRole('button', { name: label, exact: true }).click()
  await page.getByRole('menuitem', { name: command, exact: true }).click()
}

async function chooseCommand(page: Page, text: string) {
  await page.keyboard.press('Control+Shift+P')
  const input = palette(page).getByRole('combobox')
  await expect(input).toBeFocused()
  await input.fill(text)
  await input.press('Enter')
  await expect(palette(page)).toHaveCount(0)
}

async function markdown(page: Page) {
  const download = page.waitForEvent('download')
  await menu(page, 'Export', 'Download Markdown')
  return readFile(await (await download).path(), 'utf8')
}

test('the palette runs fuzzy matches, preserves keyboard navigation, and remembers commands', async ({ page }) => {
  await start(page)
  const unrelated = await page.evaluate(() => {
    const event = new KeyboardEvent('keydown', { key: 'o', ctrlKey: true, shiftKey: true, bubbles: true, cancelable: true })
    return window.dispatchEvent(event)
  })
  expect(unrelated).toBe(true)
  await chooseCommand(page, 'nw dcm')
  await expect(page.getByRole('tab', { name: 'Untitled document' })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Control+Shift+P')
  await expect(palette(page).getByText('Recently used', { exact: true })).toBeVisible()
  await expect(palette(page).getByRole('option', { name: /^New document$/ })).toHaveAttribute('aria-selected', 'true')
  const input = palette(page).getByRole('combobox')
  await input.press('ArrowDown')
  await expect(palette(page).getByRole('option', { name: /^New document$/ })).toHaveAttribute('aria-selected', 'false')
  await input.press('Escape')
  await expect(palette(page)).toHaveCount(0)
  await chooseCommand(page, 'splt edtr')
  await expect(visual(page)).toBeVisible()
  await expect(source(page)).toBeVisible()
  await chooseCommand(page, 'getting started')
  await expect(visual(page)).toContainText('Welcome to Folio')
  await chooseCommand(page, 'version history')
  await expect(page.getByRole('dialog', { name: 'Version History' })).toBeVisible()
})

test('rendered search highlights both split panes and replace-all preserves Markdown structure and undo', async ({ page }) => {
  await start(page)
  const original = ['---', 'title: needle', '---', '', '# Needle notes', '', '**needle** [needle](https://example.com/needle) NEEDLE needlework.', '',
    ':::widget', 'needle', ':::', '', '```js', 'const needle = 1', '```', ''].join('\n')
  await open(page, 'Structured', original)
  await page.getByRole('button', { name: 'Split Editor', exact: true }).click()
  await page.keyboard.press('Control+F')
  await query(page).fill('needle')
  await expect(panel(page).getByText('1 of 6 matches')).toBeVisible()
  await panel(page).getByRole('button', { name: 'Whole word' }).click()
  await panel(page).getByRole('button', { name: 'Match case' }).click()
  await expect(panel(page).getByText('1 of 3 matches')).toBeVisible()
  await expect(visual(page).locator('.folio-find-hit')).toHaveCount(3)
  await expect(source(page).locator('.folio-find-hit')).toHaveCount(3)
  await page.keyboard.press('F3')
  await expect(panel(page).getByText('2 of 3 matches')).toBeVisible()
  await page.keyboard.press('Shift+F3')
  await expect(panel(page).getByText('1 of 3 matches')).toBeVisible()
  await query(page).press('Escape')
  await page.keyboard.press('Control+H')
  await query(page).fill('needle')
  await panel(page).getByRole('button', { name: 'Whole word' }).click()
  await panel(page).getByRole('button', { name: 'Match case' }).click()
  await panel(page).getByRole('textbox', { name: 'Replace with' }).fill('thread')
  await panel(page).getByRole('button', { name: 'Replace all' }).click()
  await expect(panel(page).getByText('3 matches replaced.')).toBeVisible()
  expect(await markdown(page)).toBe(original.replace('**needle** [needle]', '**thread** [thread]').replace('const needle', 'const thread'))
  await page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true }).click()
  await expect(panel(page).getByText('1 of 3 matches')).toBeVisible()
  expect(await markdown(page)).toBe(original)
  await page.getByRole('button', { name: 'Redo (Ctrl+Shift+Z)', exact: true }).click()
  await expect(visual(page).getByText('thread', { exact: true })).toHaveCount(2)
})

test('raw regex edits in Markdown mode are undoable and protect against broken fences', async ({ page }) => {
  await start(page)
  const original = '---\ntitle: item 24\n---\n\n# Document\n\n```text\nitem 99\n```\n'
  await open(page, 'Raw', original)
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  await page.keyboard.press('Control+H')
  await panel(page).getByRole('combobox', { name: 'Search scope' }).selectOption('source')
  await panel(page).getByRole('button', { name: 'Regular expression' }).click()
  await query(page).fill('[')
  await expect(panel(page).getByRole('alert')).toHaveText('Enter a valid regular expression.')
  await query(page).fill('(?<=title: )item (\\d+)')
  await expect(panel(page).getByText('1 of 1 match')).toBeVisible()
  await panel(page).getByRole('textbox', { name: 'Replace with' }).fill('entry $1')
  await panel(page).getByRole('button', { name: 'Replace', exact: true }).click()
  expect(await markdown(page)).toBe(original.replace('title: item 24', 'title: entry 24'))
  await page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true }).click()
  expect(await markdown(page)).toBe(original)
  await panel(page).getByRole('button', { name: 'Regular expression' }).click()
  await query(page).fill('```')
  await panel(page).getByRole('textbox', { name: 'Replace with' }).fill('')
  await panel(page).getByRole('button', { name: 'Replace', exact: true }).click()
  await expect(panel(page).getByRole('alert')).toContainText('Close the Markdown code fence.')
  await panel(page).getByRole('button', { name: 'Replace all' }).click()
  await expect(panel(page).getByRole('alert')).toContainText('The replacement would change Markdown structure.')
  expect(await markdown(page)).toBe(original)
})

test('rendered replacements in Markdown mode preserve protected syntax and skip mixed formatting', async ({ page }) => {
  await start(page)
  const original = '---\ntitle: First\n---\n\n  # First\n\nFirst **second**. [First](/First)\n'
  await open(page, 'Rendered source', original)
  await page.getByRole('button', { name: 'Markdown Source', exact: true }).click()
  await page.keyboard.press('Control+H')
  await query(page).fill('First second')
  await expect(panel(page).getByText('1 of 1 match')).toBeVisible()
  await panel(page).getByRole('textbox', { name: 'Replace with' }).fill('New phrase')
  await panel(page).getByRole('button', { name: 'Replace', exact: true }).click()
  await expect(panel(page).getByText(/match spans multiple formats/)).toBeVisible()
  expect(await markdown(page)).toBe(original)
  await query(page).fill('First')
  await expect(panel(page).getByText('1 of 3 matches')).toBeVisible()
  await expect(source(page).locator('.folio-find-hit')).toHaveCount(3)
  await panel(page).getByRole('textbox', { name: 'Replace with' }).fill('Revised')
  await panel(page).getByRole('button', { name: 'Replace all' }).click()
  expect(await markdown(page)).toBe(original.replace('# First', '# Revised').replace('First **', 'Revised **').replace('[First]', '[Revised]'))
  await page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true }).click()
  expect(await markdown(page)).toBe(original)
})

test('visual replacement keeps empty paragraphs and Raw Markdown replace in Split owns source undo', async ({ page }) => {
  await start(page)
  await open(page, 'Blank paragraphs', 'hello\n')
  await visual(page).click()
  await page.keyboard.press('End')
  await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  await expect(visual(page).locator('p')).toHaveCount(3)
  await page.keyboard.press('Control+H')
  await query(page).fill('hello')
  await panel(page).getByRole('textbox', { name: 'Replace with' }).fill('bye')
  await panel(page).getByRole('button', { name: 'Replace', exact: true }).click()
  await expect(visual(page).locator('p')).toHaveCount(3)
  await expect(visual(page)).toContainText('bye')
  await page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true }).click()
  await expect(visual(page)).toContainText('hello')
  await expect(visual(page).locator('p')).toHaveCount(3)

  await open(page, 'Split raw', 'first\n\nsecond\n')
  await page.getByRole('button', { name: 'Split Editor', exact: true }).click()
  await panel(page).getByRole('combobox', { name: 'Search scope' }).selectOption('source')
  await panel(page).getByRole('button', { name: 'Regular expression' }).click()
  await query(page).fill('first\\n\\nsecond')
  await expect(panel(page).getByText('1 of 1 match')).toBeVisible()
  await expect(visual(page).locator('.folio-find-hit')).toHaveCount(2)
  await panel(page).getByRole('button', { name: 'Regular expression' }).click()
  await query(page).fill('second')
  await panel(page).getByRole('textbox', { name: 'Replace with' }).fill('updated')
  await panel(page).getByRole('button', { name: 'Replace', exact: true }).click()
  await expect(visual(page)).toContainText('updated')
  await panel(page).getByRole('button', { name: 'Close find' }).click()
  await expect(source(page)).toBeFocused()
  await page.keyboard.press('Control+Z')
  await expect(visual(page)).toContainText('second')
  expect(await markdown(page)).toBe('first\n\nsecond\n')
})

test('rendered search uses the last complete preview while Raw Markdown can edit an unfinished draft', async ({ page }) => {
  await start(page)
  await open(page, 'Incomplete draft', '# Complete heading\n')
  await page.getByRole('button', { name: 'Split Editor', exact: true }).click()
  await source(page).focus()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('\n```text\nneedle\n')
  await expect(page.getByText('Preview paused.', { exact: true })).toBeVisible()
  const draft = await markdown(page)
  expect(draft).toContain('```text\nneedle\n')
  await page.keyboard.press('Control+H')
  await query(page).fill('needle')
  await expect(panel(page).getByText('No matches', { exact: true })).toBeVisible()
  await panel(page).getByRole('combobox', { name: 'Search scope' }).selectOption('source')
  await expect(panel(page).getByText('1 of 1 match')).toBeVisible()
  await panel(page).getByRole('textbox', { name: 'Replace with' }).fill('thread')
  await panel(page).getByRole('button', { name: 'Replace', exact: true }).click()
  expect(await markdown(page)).toBe(draft.replace('needle', 'thread'))
  await expect(page.getByText('Preview paused.', { exact: true })).toBeVisible()
})

test('find follows the active tab and leaves other drafts and their histories isolated', async ({ page }) => {
  await start(page)
  await open(page, 'Alpha', '# token\n')
  await menu(page, 'File', 'Version History')
  const history = page.getByRole('dialog', { name: 'Version History' })
  await history.getByRole('button', { name: 'Create version' }).click()
  await expect(history.getByText('Version saved.')).toBeVisible()
  await history.getByRole('button', { name: 'Close dialog' }).click()
  await open(page, 'Bravo', '# token token\n')
  await page.keyboard.press('Control+H')
  await query(page).fill('token')
  await expect(panel(page).getByText('1 of 2 matches')).toBeVisible()
  await page.getByRole('tab', { name: 'Alpha', exact: true }).click()
  await expect(panel(page).getByText('1 of 1 match')).toBeVisible()
  await page.getByRole('tab', { name: 'Bravo', exact: true }).click()
  await expect(panel(page).getByText('1 of 2 matches')).toBeVisible()
  await panel(page).getByRole('textbox', { name: 'Replace with' }).fill('changed')
  await panel(page).getByRole('button', { name: 'Replace all' }).click()
  await expect(visual(page).getByRole('heading', { name: 'changed changed' })).toBeVisible()
  await expect(page.getByTitle('Saved locally')).toBeVisible()
  await page.reload()
  await expect(visual(page).getByRole('heading', { name: 'changed changed' })).toBeVisible()
  await page.getByRole('tab', { name: 'Alpha', exact: true }).click()
  await expect(visual(page).getByRole('heading', { name: 'token' })).toBeVisible()
  await menu(page, 'File', 'Version History')
  await history.getByRole('button', { name: /Preview version.*Manual/ }).click()
  await expect(page.frameLocator('iframe[title="Rendered version preview"]').getByRole('heading', { name: 'token' })).toBeVisible()
})
