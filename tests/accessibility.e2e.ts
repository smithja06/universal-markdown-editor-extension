import { expect, test, type Page } from '@playwright/test'

const visual = (page: Page) => page.getByRole('textbox', { name: 'Visual document editor' })
const source = (page: Page) => page.getByRole('textbox', { name: 'Markdown source editor' })
const button = (page: Page, name: string) => page.getByRole('button', { name, exact: true })

async function start(page: Page) {
  await page.goto('/')
  await expect(visual(page)).toContainText('Welcome to Folio')
}

async function openFromFileMenu(page: Page, action: string) {
  await button(page, 'File').press('Enter')
  await page.getByRole('menuitem', { name: action, exact: true }).press('Enter')
}

test('menus transfer keyboard focus and the library restores it after cancel and close', async ({ page }) => {
  await start(page)
  const file = button(page, 'File')
  await file.press('Enter')
  await expect(page.getByRole('menuitem', { name: 'New document', exact: true })).toBeFocused()
  await page.keyboard.press('End')
  await expect(page.getByRole('menuitem', { name: 'Duplicate document', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(file).toBeFocused()

  await openFromFileMenu(page, 'Document library')
  const library = page.getByRole('dialog', { name: 'Document library' })
  const search = library.getByRole('searchbox', { name: 'Search documents' })
  await expect(search).toBeFocused()
  await page.keyboard.type('Getting started')
  const rename = library.getByRole('button', { name: 'Rename Getting started' })
  await rename.press('Enter')
  await expect(library.getByRole('textbox', { name: 'Document name' })).toBeFocused()
  await library.getByRole('button', { name: 'Cancel', exact: true }).press('Enter')
  await expect(rename).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(library).toHaveCount(0)
  await expect(file).toBeFocused()
})

test('open documents use a single tab stop and keep the selected tab visible', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 760 })
  await start(page)
  const add = button(page, 'New document tab')
  const list = page.getByRole('tablist', { name: 'Open documents' })
  const strip = page.locator('.document-tab-strip')
  const tabs = strip.getByRole('tab')
  for (let count = 2; count <= 7; count++) {
    await add.press('Enter')
    await expect(tabs).toHaveCount(count)
  }
  const first = tabs.first()
  const last = tabs.last()
  const ids = await tabs.evaluateAll(elements => elements.map(element => element.id).join(' '))
  await expect(list).toHaveAttribute('aria-owns', ids)
  await last.focus()
  await page.keyboard.press('Home')
  await expect(first).toBeFocused()
  await expect(first).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Tab')
  await expect(add).toBeFocused()

  await first.focus()
  await page.keyboard.press('End')
  await expect(last).toBeFocused()
  await expect(last).toHaveAttribute('aria-selected', 'true')
  await expect(last).toBeInViewport()
  await page.keyboard.press('Delete')
  await expect(tabs).toHaveCount(6)
  await expect(strip.getByRole('tab', { selected: true })).toBeFocused()
})

test('narrow toolbar keeps essential controls in one row and exposes overflow by keyboard', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 760 })
  await start(page)
  const toolbar = page.getByRole('toolbar', { name: 'Formatting controls' })
  const overflow = toolbar.getByRole('button', { name: 'More formatting' })
  expect((await toolbar.boundingBox())?.height).toBeLessThan(47)
  await expect(toolbar.getByRole('button', { name: /^Bold/ })).toBeVisible()
  await expect(toolbar.getByRole('button', { name: 'Insert content' })).toBeVisible()
  await overflow.press('Enter')
  const menu = toolbar.getByRole('menu', { name: 'More formatting' })
  await expect(menu.getByRole('menuitem', { name: 'Text color – Ocean' })).toBeVisible()
  await expect(menu.getByRole('menuitem', { name: 'Task list' })).toBeVisible()
  const bounds = await menu.boundingBox()
  expect(bounds?.x).toBeGreaterThanOrEqual(0)
  expect((bounds?.x ?? 0) + (bounds?.width ?? 0)).toBeLessThanOrEqual(320)
  await page.keyboard.press('Escape')
  await expect(overflow).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})

test('the palette pages results and restores editor focus in a dark tablet layout', async ({ page }) => {
  await page.setViewportSize({ width: 834, height: 900 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await start(page)
  await button(page, 'View').press('Enter')
  await page.getByRole('menuitem', { name: 'Appearance', exact: true }).press('Enter')
  const theme = page.getByRole('combobox', { name: 'Theme' })
  await theme.press('End')
  await expect(theme).toHaveValue('dark')
  await expect(page.locator('.app')).toHaveCSS('color-scheme', 'dark')

  await visual(page).focus()
  await page.keyboard.press('Control+Shift+P')
  const palette = page.getByRole('dialog', { name: 'Command Palette' })
  const query = palette.getByRole('combobox')
  await expect(query).toBeFocused()
  await expect(palette.getByRole('status')).toContainText(/\d+ results/)
  const first = await query.getAttribute('aria-activedescendant')
  await page.keyboard.press('PageDown')
  await expect(query).not.toHaveAttribute('aria-activedescendant', first ?? '')
  await page.keyboard.press('PageUp')
  await expect(query).toHaveAttribute('aria-activedescendant', first ?? '')
  await page.keyboard.press('Escape')
  await expect(visual(page)).toBeFocused()
})

