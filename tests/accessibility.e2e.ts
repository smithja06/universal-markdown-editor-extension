test('macOS command bindings are routed through the macOS keyboard profile', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'platform', { get: () => 'MacIntel' }))
  await start(page)
  const palette = page.getByRole('dialog', { name: 'Command Palette' })
  await visual(page).focus()
  await page.keyboard.press('Control+Shift+P')
  await expect(palette).toHaveCount(0)
  await page.keyboard.press('Meta+Shift+P')
  await expect(palette.getByRole('combobox')).toBeFocused()
  await page.keyboard.press('Escape')
  await page.keyboard.press('Meta+Alt+f')
  const find = page.getByRole('region', { name: 'Find and replace' })
  await expect(find.getByRole('textbox', { name: 'Find text' })).toBeFocused()
  await expect(find.getByRole('textbox', { name: 'Replace with' })).toBeVisible()
})

test('forced colors distinguish the current match from the other matches', async ({ page }) => {
  await page.emulateMedia({ forcedColors: 'active' })
  await start(page)
  await visual(page).focus()
  await page.keyboard.press('Control+F')
  const find = page.getByRole('region', { name: 'Find and replace' })
  await find.getByRole('textbox', { name: 'Find text' }).fill('o')
  await expect(visual(page).locator('.folio-find-current').first()).toHaveCSS('outline-width', '2px')
  await expect(visual(page).locator('.folio-find-hit:not(.folio-find-current)').first()).toHaveCSS('outline-style', 'dashed')
})

test('the Find command refocuses an existing panel after the palette closes', async ({ page }) => {
  await start(page)
  await visual(page).focus()
  await page.keyboard.press('Control+F')
  const find = page.getByRole('region', { name: 'Find and replace' })
  const search = find.getByRole('textbox', { name: 'Find text' })
  await search.fill('Welcome')
  await visual(page).focus()
  await page.keyboard.press('Control+Shift+P')
  const palette = page.getByRole('dialog', { name: 'Command Palette' })
  const command = palette.getByRole('combobox')
  await command.fill('Find and replace')
  await command.press('Enter')
  await expect(palette).toHaveCount(0)
  await expect(search).toBeFocused()
  await page.keyboard.type('Folio')
  await expect(search).toHaveValue('Folio')
})
