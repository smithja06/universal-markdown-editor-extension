test('split panes resize by keyboard and Find preserves focus and announces the active match', async ({ page }) => {
  await page.setViewportSize({ width: 834, height: 900 })
  await start(page)
  await button(page, 'Split Editor').press('Enter')
  const divider = page.getByRole('separator', { name: 'Resize editor panes' })
  await divider.press('End')
  await expect(divider).toHaveAttribute('aria-valuenow', await divider.getAttribute('aria-valuemax') ?? '')
  await divider.press('Home')
  await expect(divider).toHaveAttribute('aria-valuenow', await divider.getAttribute('aria-valuemin') ?? '')

  await source(page).focus()
  await page.keyboard.press('Control+F')
  const find = page.getByRole('region', { name: 'Find and replace' })
  const query = find.getByRole('textbox', { name: 'Find text' })
  await expect(query).toBeFocused()
  await page.keyboard.type('Welcome')
  await expect(find.getByRole('status')).toHaveText('1 of 1 match')
  await expect(visual(page).locator('.folio-find-current')).toBeVisible()
  await expect(source(page).locator('.folio-find-current')).toBeVisible()
  await find.getByRole('button', { name: 'Show replacement' }).press('Enter')
  await expect(find.getByRole('button', { name: 'Hide replacement' })).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await expect(source(page)).toBeFocused()

  await page.setViewportSize({ width: 360, height: 760 })
  await expect(divider).toBeHidden()
  await expect(source(page)).toBeVisible()
  await expect(visual(page)).toBeVisible()
})

test('canceling a version restore returns focus to Restore version', async ({ page }) => {
  await start(page)
  await openFromFileMenu(page, 'Version History')
  const history = page.getByRole('dialog', { name: 'Version History' })
  await history.getByRole('button', { name: /Preview version.*Automatic/ }).first().press('Enter')
  const restore = history.getByRole('button', { name: 'Restore version', exact: true })
  await restore.press('Enter')
  await expect(history.getByRole('button', { name: 'Cancel restore' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(restore).toBeFocused()
})

